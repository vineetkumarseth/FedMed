import socket

import pytest


def free_port(n: int = 1):
    socks, ports = [], []
    for _ in range(n):
        s = socket.socket()
        s.bind(("127.0.0.1", 0))
        socks.append(s)
        ports.append(s.getsockname()[1])
    for s in socks:
        s.close()
    return ports


@pytest.fixture
def ports():
    return free_port(5)
